_INDEX_NAME = "ix_embeddings_embedding_hnsw"


def upgrade() -> None:
    """Restore the approximate-nearest-neighbour index on the vector column.

    The first schema revision created an HNSW index, and a later autogenerated
    revision dropped it because the model never declared it -- the index existed
    in the database but not in ``Base.metadata``, so the drift check classified
    it as something to remove. It was not a deliberate performance decision. The
    model now declares the same index, which is what stops a future autogenerate
    from dropping it again.

    The index matters once retrieval runs more than once per question: an exact
    scan reads every vector in the table, so its cost grows with the number of
    ingested repositories. HNSW bounds that to a walk of the graph.

    ``CONCURRENTLY`` cannot run inside the transaction ``env.py`` wraps an
    upgrade in, so the build happens in its own autocommit block. If it is
    interrupted mid-build the index is left ``INVALID`` and unusable; recover
    with ``DROP INDEX CONCURRENTLY IF EXISTS <name>`` and re-run.

    ``IF NOT EXISTS`` keeps a re-run a no-op: the test database is migrated once
    per xdist worker, and two workers can reach an unmigrated database at the
    same time. ``m`` and ``ef_construction`` use the documented defaults,
    written out so the shape is visible here rather than inherited silently.
    """
    with op.get_context().autocommit_block():
        op.execute(
            f"""
            CREATE INDEX CONCURRENTLY IF NOT EXISTS {_INDEX_NAME}
            ON embeddings USING hnsw (embedding vector_cosine_ops)
            WITH (m = 16, ef_construction = 64)
            """
        )


def downgrade() -> None:
    """Drop the index, concurrently because the table is live in production."""
    with op.get_context().autocommit_block():
        op.execute(f"DROP INDEX CONCURRENTLY IF EXISTS {_INDEX_NAME}")
